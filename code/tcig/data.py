"""TopCoW processed-volume dataset for TCIG.

The current dataset deliberately returns images and labels only. Interaction
histories are generated by the training/evaluation loops from model
predictions so the click distribution matches inference.
"""

from __future__ import annotations

import json
import random
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np
import torch
from torch.utils.data import Dataset


Record = Dict[str, object]


def split_manifest_records(
    records: Sequence[Record],
    *,
    split: str = "train",
    val_fraction: float = 0.2,
    seed: int = 7,
) -> List[Record]:
    """Return a deterministic train/val/all partition.

    TopCoW's current processed split file marks all 125 cases as train. For
    method development we therefore use a deterministic manifest-level split
    so training and NoC validation do not evaluate on the exact same cases by
    accident.
    """
    if split not in ("train", "val", "all"):
        raise ValueError("split must be one of: train, val, all")
    if not 0.0 <= val_fraction < 1.0:
        raise ValueError("val_fraction must be in [0, 1)")

    rows = list(records)
    if split == "all" or val_fraction == 0.0:
        return rows

    indices = list(range(len(rows)))
    rng = random.Random(seed)
    rng.shuffle(indices)
    val_count = max(1, int(round(len(indices) * val_fraction))) if len(indices) > 1 else 1
    val_set = set(indices[:val_count])

    if split == "val":
        return [row for idx, row in enumerate(rows) if idx in val_set]
    return [row for idx, row in enumerate(rows) if idx not in val_set]


class TopCoWVolumeDataset(Dataset):
    """Read TopCoW `.npy` volumes from a TCIG manifest.

    Parameters
    ----------
    manifest:
        JSONL manifest generated by `scripts/build_manifest.py`.
    data_root:
        Root directory containing `image/`, `binary_label/`, and optionally
        `multiclass_mask/`.
    patch_size:
        Optional `(D, H, W)` crop size. `None` returns full volumes.
    deterministic:
        If true, crops use a stable foreground-centered anchor per case. Use it
        for validation; keep it false for training augmentation.
    split:
        `train`, `val`, or `all` manifest partition.
    """

    def __init__(
        self,
        manifest: Path,
        data_root: Path,
        *,
        patch_size: Optional[Tuple[int, int, int]] = None,
        split: str = "train",
        val_fraction: float = 0.2,
        seed: int = 7,
        max_cases: int = 0,
        deterministic: bool = False,
    ) -> None:
        self.manifest = Path(manifest)
        self.data_root = Path(data_root)
        self.patch_size = patch_size
        self.seed = int(seed)
        self.deterministic = bool(deterministic)

        records = _read_jsonl(self.manifest)
        records = split_manifest_records(records, split=split, val_fraction=val_fraction, seed=seed)
        if max_cases > 0:
            records = records[:max_cases]
        if not records:
            raise ValueError(f"no records selected from manifest={manifest} split={split}")
        self.records = records

    def __len__(self) -> int:
        return len(self.records)

    def __getitem__(self, index: int) -> Dict[str, object]:
        record = self.records[index % len(self.records)]
        case_id = str(record.get("case_id", index))
        if record.get("label") is None:
            raise ValueError(f"record has no label path: {case_id}")

        image = np.load(self.data_root / str(record["image"])).astype(np.float32)
        label = np.load(self.data_root / str(record["label"])).astype(np.float32)
        _validate_volume_pair(image, label, case_id)

        origin = (0, 0, 0)
        if self.patch_size is not None:
            rng = random.Random(self.seed + index) if self.deterministic else random
            image, label, origin = _crop_pair(image, label, self.patch_size, rng=rng)

        return {
            "case_id": case_id,
            "image": torch.from_numpy(image[None, ...]),
            "label": torch.from_numpy(label[None, ...]),
            "origin": torch.tensor(origin, dtype=torch.long),
            "record": record,
        }


def collate_topcow_batch(items: List[Dict[str, object]]) -> Dict[str, object]:
    """Batch TopCoW items.

    Current training supports `batch_size=1` because every sample owns a
    variable-length interactive history. The explicit collate keeps the error
    message honest instead of failing deeper in the graph code.
    """
    if len(items) != 1:
        raise ValueError("TCIG currently supports batch_size=1 for interactive histories")
    item = items[0]
    return {
        "case_id": item["case_id"],
        "image": item["image"].unsqueeze(0),
        "label": item["label"].unsqueeze(0),
        "origin": item["origin"].unsqueeze(0),
        "record": item["record"],
    }


def _read_jsonl(path: Path) -> List[Record]:
    with path.open("r", encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def _validate_volume_pair(image: np.ndarray, label: np.ndarray, case_id: str) -> None:
    if image.ndim != 3 or label.ndim != 3:
        raise ValueError(f"case {case_id} must contain 3D arrays, got {image.shape} and {label.shape}")
    if image.shape != label.shape:
        raise ValueError(f"case {case_id} image/label shape mismatch: {image.shape} vs {label.shape}")


def _crop_pair(
    image: np.ndarray,
    label: np.ndarray,
    patch_size: Tuple[int, int, int],
    *,
    rng,
) -> Tuple[np.ndarray, np.ndarray, Tuple[int, int, int]]:
    if len(patch_size) != 3 or any(size < 2 for size in patch_size):
        raise ValueError("patch_size must contain three values >= 2")

    foreground = np.argwhere(label > 0.5)
    anchor = None
    if len(foreground) > 0:
        anchor = foreground[rng.randrange(len(foreground))]

    starts = []
    for axis, (dim, size) in enumerate(zip(image.shape, patch_size)):
        if dim <= size:
            starts.append(0)
        elif anchor is not None:
            low = max(0, int(anchor[axis]) - size + 1)
            high = min(int(anchor[axis]), dim - size)
            starts.append(rng.randint(low, high))
        else:
            starts.append(rng.randint(0, dim - size))

    slices = tuple(slice(start, start + size) for start, size in zip(starts, patch_size))
    return image[slices], label[slices], tuple(int(v) for v in starts)
